class HTMLReporter:
  def __init__(self, out: str = 'report.html'):
    self.out = out

  def _map_severity(self, sev):
    # Accept either Severity enum or string
    s = str(sev)
    if 'HIGH' in s.upper():
      return ('高', 'high')
    if 'MEDIUM' in s.upper():
      return ('中', 'medium')
    if 'INFO' in s.upper():
      return ('信息', 'info')
    return ('低', 'low')

  def report(self, findings: List[Finding], metadata: Dict[str, Any] = None):
    rows = []
    summary = {'high': 0, 'medium': 0, 'low': 0, 'info': 0, 'total': 0}

    for f in findings:
      sev_cn, sev_class = self._map_severity(getattr(f, 'severity', 'LOW'))
      rows.append({
        'severity': str(getattr(f, 'severity', 'LOW')),
        'severity_cn': sev_cn,
        'severity_class': sev_class,
        'scanner': escape(f.scanner),
        'message': escape(f.message),
        'file': escape(f.file or ''),
        'line': f.line,
        'rule_id': escape(f.rule_id or ''),
        'recommendation': escape(f.recommendation or ''),
        'category': escape(f.category or ''),
        'evidence': escape(f.evidence or ''),
        'confidence': f"{f.confidence:.2f}",
      })
      summary[sev_class] += 1
      summary['total'] += 1

    tpl = Template(HTML_TMPL)
    with open(self.out, 'w', encoding='utf8') as fh:
      fh.write(
        tpl.render(
          findings=rows,
          summary=summary,
          scan_time=(metadata.get('scan_time') if metadata else ''),
          scanned_path=escape(metadata.get('scanned_path') if metadata else ''),
          scanner_stats=(metadata.get('scanner_stats') if metadata else {}),
        )
      )
